# Used to initialize weights for policy and value output layers
def normalized_columns_initializer(std=1.0):
    """
    Returns an initializer function that generates random values from a normal
    distribution and normalizes columns to have unit variance.
    
    Parameters
    ----------
    std : float, optional
        Standard deviation of the normal distribution (default: 1.0).

    Returns
    -------
    initializer : keras.initializers.Initializer
        Initializer for Keras layers.
    """
    class NormalizedColumnsInitializer(keras.initializers.Initializer):
        def __init__(self, std=1.0):
            self.std = std
        
        def __call__(self, shape, dtype=None):
            # Generate random values from a normal distribution
            out = np.random.randn(*shape).astype(np.float32)
            
            # Normalize columns to have unit variance
            out *= self.std / np.sqrt(np.square(out).sum(axis=0, keepdims=True))
            
            return tf.constant(out, dtype=dtype)
        
        def get_config(self):
            return {'std': self.std}
    
    return NormalizedColumnsInitializer(std)


# Discounting function used to calculate discounted returns
def discount(x, gamma):
    """
    Apply discounting to a sequence of values using a linear filter.

    Parameters
    ----------
    x : numpy.ndarray
        Obtained sequence of rewards to be discounted.
    gamma : float
        Discount factor, where 0 <= gamma <= 1.

    Returns
    -------
    discounted_returns : numpy.ndarray
        Discounted sequence of values.
    """
    # Apply a linear filter to calculate discounted returns
    discounted_returns = signal.lfilter([1], [1, -gamma], x[::-1], axis=0)[::-1]
    return discounted_returns


class ConditioningBandit:
    """
    Class to handle agent bandit interactions.

    Parameters
    ----------
    game : bandit instance from one of the bandit classes
        Bandit instance providing the underlying bandit rewards and probabilities.

    Attributes
    ----------
    game : bandit instance
        Bandit instance providing rewards and probabilities.
    timestep : int
        Current timestep in the bandit interaction.
    restless_rewards : numpy.ndarray
        Sequence of rewards generated by the bandits.
    reward_probs : numpy.ndarray
        Probability of rewards for each arm at each timestep.
    bandit : numpy.ndarray
        Rewards of the current timestep.

    Methods
    -------
    set_restless_prob()
        Set the current rewards based on the restless rewards at the current timestep.
    reset()
        Reset the bandit, generating new restless rewards and reward probabilities.
    pull_arm(action)
        Simulate pulling an arm of the bandit at the current timestep.
    update()
        Update the timestep and set the current bandit accordingly.
    """

    def __init__(self, game):
        """Initialize the ConditioningBandit instance."""
        self.game = game
        self.reset()

    def set_restless_prob(self):
        """Set the current bandit based on the restless rewards at the current timestep."""
        self.bandit = self.restless_rewards[self.timestep]

    def reset(self):
        """Reset the bandit, generating new restless rewards and reward probabilities."""
        self.timestep = 0
        rewards, reward_probs = self.game.generate_task()
        self.restless_rewards = rewards
        self.reward_probs = reward_probs
        self.set_restless_prob()

    def pull_arm(self, action):
        """
        Simulate pulling an arm of the bandit at the current timestep.

        Parameters
        ----------
        action : int
            Chosen arm index.

        Returns
        -------
        reward : float
            Reward for the chosen arm.
        done : bool
            Whether the interaction is done.
        timestep : int
            Current timestep.
        """
        if self.timestep >= (len(self.restless_rewards) - 1):
            done = True
        else:
            done = False
        return self.bandit[int(action)], done, self.timestep

    def update(self):
        """Update the timestep and set the current bandit accordingly."""
        self.timestep += 1
        self.set_restless_prob()


class AC_Network(keras.Model):
    """
    Actor-Critic Network using TensorFlow 2 / Keras.
    
    Parameters
    ----------
    noise : str
        Type of computational noise:
        - 'none'
        - 'update-dependant' (Weber Noise, as in Findling & Wyart, 2020)
        - 'constant' (not implemented yet)
    rnn_type : str
        Type of RNN cell:
        - 'lstm' (standard LSTM)
        - 'lstm2' (custom LSTM with noise if noise == 'update-dependant')
        - 'rnn' (Elman RNN)
    noise_parameter : float
        Weber fraction (default = 0.5).
    n_hidden_neurons : int
        Number of units in the hidden layer.
    n_arms : int
        Number of arms in the bandit.
    entropy_loss_weight : float or str
        Weight for the entropy loss:
        - 'linear' if entropy should be linearly decreasing from 1 to 0
        - float value between 0-1
    value_loss_weight : float
        Weight for the value loss.
    learning_algorithm : str
        Learning algorithm:
        - 'a2c' (Advantage-Actor-Critic)
        - 'reinforce'
    """
    
    def __init__(self, noise, rnn_type, noise_parameter,
                 n_hidden_neurons, n_arms, entropy_loss_weight,
                 value_loss_weight, learning_algorithm):
        super(AC_Network, self).__init__()
        
        self.noise = noise
        self.rnn_type = rnn_type
        self.noise_parameter = noise_parameter
        self.n_hidden_neurons = n_hidden_neurons
        self.n_arms = n_arms
        self.entropy_loss_weight_param = entropy_loss_weight
        self.value_loss_weight = value_loss_weight
        self.learning_algorithm = learning_algorithm
        
        # Build the RNN layer based on type
        if rnn_type == 'lstm' and noise == 'none':
            # Standard Keras LSTM
            self.rnn_cell = layers.LSTMCell(n_hidden_neurons)
            self.rnn = layers.RNN(self.rnn_cell, return_sequences=True, return_state=True)
            
        elif rnn_type == 'lstm2' and noise == 'update-dependant':
            # Custom LSTM with noise
            self.rnn_cell = own_lstm_cell_tf2.LSTM(n_arms + 1, n_hidden_neurons, add_noise=True)
            
        elif rnn_type == 'rnn':
            # Custom RNN
            add_noise = (noise == 'update-dependant')
            self.rnn_cell = recurrent_networks_tf2.RNN(n_arms + 1, n_hidden_neurons, add_noise)
        else:
            raise ValueError(f"Invalid combination of rnn_type={rnn_type} and noise={noise}")
        
        # Policy head (actor)
        self.policy_head = layers.Dense(
            n_arms,
            activation='softmax',
            kernel_initializer=normalized_columns_initializer(0.01),
            use_bias=False,
            name='policy'
        )
        
        # Value head (critic) - only for A2C
        if learning_algorithm == 'a2c':
            self.value_head = layers.Dense(
                1,
                activation=None,
                kernel_initializer=normalized_columns_initializer(1.0),
                use_bias=False,
                name='value'
            )
    
    def get_initial_state(self, batch_size=1):
        """Get initial RNN state."""
        if self.rnn_type == 'lstm':
            h = tf.zeros([batch_size, self.n_hidden_neurons])
            c = tf.zeros([batch_size, self.n_hidden_neurons])
            return (h, c)
        elif self.rnn_type == 'lstm2':
            return self.rnn_cell.get_initial_state(batch_size)
        elif self.rnn_type == 'rnn':
            return self.rnn_cell.get_initial_state(batch_size)
    
    def call(self, inputs, states=None, h_noise=None, training=False):
        """
        Forward pass through the network.
        
        Parameters
        ----------
        inputs : dict
            Dictionary containing:
            - 'prev_rewards': shape [batch_size, 1]
            - 'prev_actions': shape [batch_size, n_arms] (one-hot)
        states : tuple
            RNN states (h, c) for LSTM or (h,) for RNN.
        h_noise : tf.Tensor, optional
            Noise to add to hidden states. Shape: [batch_size, n_hidden_neurons]
        training : bool
            Whether in training mode.
            
        Returns
        -------
        policy : tf.Tensor
            Action probabilities. Shape: [batch_size, n_arms]
        value : tf.Tensor or None
            State value (only for A2C). Shape: [batch_size, 1]
        new_states : tuple
            Updated RNN states.
        """
        # Concatenate inputs
        input_tensor = tf.concat([inputs['prev_rewards'], inputs['prev_actions']], axis=1)
        
        # Initialize states if not provided
        if states is None:
            states = self.get_initial_state(tf.shape(input_tensor)[0])
        
        # Process through RNN
        if self.rnn_type == 'lstm' and self.noise == 'none':
            # Standard LSTM
            # Add time dimension for RNN layer
            input_tensor = tf.expand_dims(input_tensor, axis=1)
            rnn_output, h, c = self.rnn(input_tensor, initial_state=states, training=training)
            rnn_output = tf.squeeze(rnn_output, axis=1)
            new_states = (h, c)
            
        elif self.rnn_type == 'lstm2':
            # Custom LSTM with noise
            if h_noise is not None and self.noise == 'update-dependant':
                # Concatenate input with noise
                input_with_noise = tf.concat([input_tensor, h_noise], axis=1)
            else:
                input_with_noise = input_tensor
            
            rnn_output, new_states = self.rnn_cell(input_with_noise, states, training=training)
            
        elif self.rnn_type == 'rnn':
            # Custom RNN
            if h_noise is not None and self.noise == 'update-dependant':
                # Concatenate input with noise
                input_with_noise = tf.concat([input_tensor, h_noise], axis=1)
            else:
                input_with_noise = input_tensor
            
            rnn_output, new_states = self.rnn_cell(input_with_noise, states, training=training)
        
        # Compute policy (actor output)
        policy = self.policy_head(rnn_output)
        
        # Compute value (critic output) if using A2C
        if self.learning_algorithm == 'a2c':
            value = self.value_head(rnn_output)
        else:
            value = None
        
        return policy, value, new_states


class Worker:
    """
    Worker class to handle training and testing of an RL RNN agent.
    
    Methods
    -------
    train_step(rollout, gamma, bootstrap_value, entr_):
        Performs one training step using the episode rollout.
    work(gamma, train):
        Runs episodes and collects data for training or testing.
    """
    
    def __init__(self, game, optimizer, model_path, model_name, noise,
                 path_to_save_progress, n_hidden_neurons, n_arms, num_steps,
                 n_iterations, rnn_type, noise_parameter, entropy_loss_weight,
                 value_loss_weight, learning_algorithm):
        
        self.model_path = model_path
        self.optimizer = optimizer
        self.episode_rewards = []
        self.episode_lengths = []
        self.addnoises_mean_values = []
        self.hidden_mean_values = []
        self.episode_reward_reversal = []
        self.summary_writer = tf.summary.create_file_writer(path_to_save_progress + str(model_name))
        
        # Create the AC network
        self.ac_network = AC_Network(
            noise=noise,
            rnn_type=rnn_type,
            noise_parameter=noise_parameter,
            n_hidden_neurons=n_hidden_neurons,
            n_arms=n_arms,
            entropy_loss_weight=entropy_loss_weight,
            value_loss_weight=value_loss_weight,
            learning_algorithm=learning_algorithm
        )
        
        self.env = game
        self.num_steps = num_steps
        self.n_iterations = n_iterations
        self.n_hidden_neurons = n_hidden_neurons
        self.n_arms = n_arms
        self.learning_algorithm = learning_algorithm
        self.rnn_type = rnn_type
        self.noise_parameter = noise_parameter
        self.noise = noise
        self.entropy_loss_weight = entropy_loss_weight
        self.value_loss_weight = value_loss_weight
    
    @tf.function(reduce_retracing=True)
    def compute_loss(self, rollout_data, gamma, bootstrap_value, entr_):
        """
        Compute the loss for the rollout using TensorFlow operations.
        
        Parameters
        ----------
        rollout_data : dict
            Dictionary containing rollout data tensors.
        gamma : float
            Discount factor.
        bootstrap_value : float
            Bootstrap value for the last state.
        entr_ : float
            Entropy loss weight coefficient.
            
        Returns
        -------
        total_loss : tf.Tensor
            Total loss.
        losses_dict : dict
            Dictionary of individual loss components.
        """
        # Extract data from rollout
        prev_rewards = rollout_data['prev_rewards']
        prev_actions_oh = rollout_data['prev_actions_oh']
        actions = rollout_data['actions']
        h_noises = rollout_data['h_noises']
        discounted_rewards = rollout_data['discounted_rewards']
        
        # Initialize RNN state
        batch_size = 1
        rnn_state = self.ac_network.get_initial_state(batch_size)
        
        # Forward pass through network
        all_policies = []
        all_values = []
        
        for t in range(prev_rewards.shape[0]):
            inputs = {
                'prev_rewards': prev_rewards[t:t+1],
                'prev_actions': prev_actions_oh[t:t+1]
            }
            
            policy, value, rnn_state = self.ac_network(
                inputs, rnn_state, h_noises[t:t+1], training=True
            )
            
            all_policies.append(policy)
            if value is not None:
                all_values.append(value)
        
        all_policies = tf.concat(all_policies, axis=0)
        
        # Compute policy loss
        actions_oh = tf.one_hot(actions, self.n_arms)
        responsible_outputs = tf.reduce_sum(all_policies * actions_oh, axis=1)
        
        if self.learning_algorithm == 'a2c':
            all_values = tf.concat(all_values, axis=0)
            all_values_flat = tf.reshape(all_values, [-1])
            
            # Compute advantages
            value_plus = tf.concat([all_values_flat, [bootstrap_value]], axis=0)
            rewards = rollout_data['rewards']
            advantages = rewards + gamma * value_plus[1:] - value_plus[:-1]
            
            # Compute value loss
            value_loss = 0.5 * tf.reduce_sum(tf.square(discounted_rewards - all_values_flat))
            
            # Compute policy loss
            policy_loss = -tf.reduce_sum(tf.math.log(responsible_outputs + 1e-7) * advantages)
        else:
            # REINFORCE
            policy_loss = -tf.reduce_sum(tf.math.log(responsible_outputs + 1e-7) * discounted_rewards)
            value_loss = 0.0
        
        # Compute entropy
        entropy = -tf.reduce_sum(all_policies * tf.math.log(all_policies + 1e-7))
        
        # Total loss
        if self.learning_algorithm == 'a2c':
            total_loss = (self.value_loss_weight * value_loss + 
                         policy_loss - entr_ * entropy)
        else:
            total_loss = policy_loss - entr_ * entropy
        
        # Normalize by rollout length
        rollout_length = tf.cast(tf.shape(prev_rewards)[0], tf.float32)
        
        return total_loss, {
            'value_loss': value_loss / rollout_length,
            'policy_loss': policy_loss / rollout_length,
            'entropy': entropy / rollout_length
        }
    
    def train_step(self, rollout, gamma, bootstrap_value, entr_):
        """
        Perform one training step with gradient update.
        
        Parameters
        ----------
        rollout : list
            List of (action, reward, timestep, noise, value, done) tuples.
        gamma : float
            Discount factor.
        bootstrap_value : float
            Bootstrap value for last state.
        entr_ : float
            Entropy coefficient.
            
        Returns
        -------
        losses : tuple
            (value_loss, policy_loss, entropy, noise_mean, var_norm, grad_norm)
        """
        # Convert rollout to arrays
        rollout = np.array(rollout, dtype=object)
        actions = rollout[:, 0].astype(np.int32)
        rewards_ch = rollout[:, 1].astype(np.float32)
        timesteps = rollout[:, 2].astype(np.float32)
        h_noises = np.vstack(rollout[:, 3]).astype(np.float32)
        
        # Prepare previous actions and rewards
        prev_actions = np.array([2] + actions[:-1].tolist(), dtype=np.int32)
        prev_actions_oh = tf.one_hot(prev_actions, self.n_arms).numpy()
        prev_rewards_ch = np.array([0.0] + rewards_ch[:-1].tolist(), dtype=np.float32).reshape(-1, 1)
        
        # Compute discounted rewards
        rewards_plus = np.append(rewards_ch, bootstrap_value)
        discounted_rewards = discount(rewards_plus, gamma)[:-1].astype(np.float32)
        
        # Prepare rollout data as tensors
        rollout_data = {
            'prev_rewards': tf.constant(prev_rewards_ch, dtype=tf.float32),
            'prev_actions_oh': tf.constant(prev_actions_oh, dtype=tf.float32),
            'actions': tf.constant(actions, dtype=tf.int32),
            'rewards': tf.constant(rewards_ch, dtype=tf.float32),
            'h_noises': tf.constant(h_noises, dtype=tf.float32),
            'discounted_rewards': tf.constant(discounted_rewards, dtype=tf.float32)
        }
        
        # Perform gradient update
        with tf.GradientTape() as tape:
            total_loss, losses_dict = self.compute_loss(rollout_data, gamma, bootstrap_value, entr_)
        
        # Compute gradients
        trainable_vars = self.ac_network.trainable_variables
        gradients = tape.gradient(total_loss, trainable_vars)
        
        # Compute gradient and variable norms
        grad_norm = tf.linalg.global_norm(gradients)
        var_norm = tf.linalg.global_norm(trainable_vars)
        
        # Apply gradients
        self.optimizer.apply_gradients(zip(gradients, trainable_vars))
        
        # Return losses
        if self.learning_algorithm == 'a2c':
            return (losses_dict['value_loss'].numpy(),
                    losses_dict['policy_loss'].numpy(),
                    losses_dict['entropy'].numpy(),
                    0.0,
                    var_norm.numpy(),
                    grad_norm.numpy())
        else:
            return (losses_dict['policy_loss'].numpy(),
                    losses_dict['entropy'].numpy(),
                    0.0,
                    var_norm.numpy(),
                    grad_norm.numpy())
    
    def work(self, gamma, checkpoint, train):
        """
        Run episodes for training or testing.
        
        Parameters
        ----------
        gamma : float
            Discount factor.
        checkpoint : tf.train.Checkpoint
            Checkpoint object for saving/loading.
        train : bool
            Whether to train (True) or test (False).
            
        Returns
        -------
        df : pd.DataFrame (if train=False)
            Test results dataframe.
        None (if train=True)
        """
        # Prepare test dataframe if testing
        if train == False:
            rnn_state_col_names = [f'rnn_state_{i+1}' for i in range(self.n_hidden_neurons)]
            rnn_state_noise_col_names = [f'added_noise_rnn_state_{i+1}' for i in range(self.n_hidden_neurons)]
            rnn_prob_rew = [f'p_rew_{i+1}' for i in range(self.n_arms)]
            rnn_softmax = [f'softmax_{i+1}' for i in range(self.n_arms)]
            
            if self.env.game.bandit_type == 'restless':
                bandit_par = 'sd_noise'
            elif self.env.game.bandit_type == 'stationary':
                bandit_par = 'p_rew_best'
            else:
                bandit_par = 'bandit parameter'
            
            colnames = [bandit_par, 'choice', 'reward', 'value']
            colnames.extend(rnn_prob_rew + rnn_softmax + rnn_state_col_names + rnn_state_noise_col_names)
            df = pd.DataFrame(columns=colnames)
            
            my_a = []
            my_rch = []
            my_r_prob = np.zeros([self.num_steps, self.n_arms])
            rnn_softmax_arr = np.zeros([self.num_steps, self.n_arms])
            rnn_state_arr = np.zeros([self.num_steps, self.n_hidden_neurons])
            rnn_value_arr = np.zeros([self.num_steps])
            rnn_state_noise_arr = np.zeros([self.num_steps, self.n_hidden_neurons])
        
        # Get episode count if model exists
        if os.path.exists(self.model_path):
            list_of_files = glob.glob(self.model_path + '/*')
            list_of_files = [f for f in list_of_files if 'checkpoint' not in f and '.index' not in f and '.data' not in f]
            if list_of_files:
                latest_file = max(list_of_files, key=os.path.getctime)
                try:
                    episode_count = int(latest_file.split('-')[-1])
                except:
                    episode_count = 0
            else:
                episode_count = 0
        else:
            episode_count = 0
        
        entr_ = 1.0
        
        while True:
            episode_buffer = []
            episode_reward = 0
            episode_step_count = 0
            d, a, t, rch = False, 2, 0, 0.0
            
            # Initialize RNN state
            rnn_state = self.ac_network.get_initial_state(batch_size=1)
            
            self.env.reset()
            
            while d == False:
                # Generate noise
                if self.noise == 'update-dependant':
                    if self.rnn_type == 'lstm2':
                        h_noise = np.random.normal(size=(1, self.n_hidden_neurons)) * self.noise_parameter
                    else:
                        h_noise = np.random.normal(size=(1, self.n_hidden_neurons)) * self.noise_parameter
                elif self.noise == 'none':
                    h_noise = np.zeros((1, self.n_hidden_neurons))
                else:
                    raise ValueError('Constant noise not implemented yet!')
                
                h_noise = h_noise.astype(np.float32)
                
                # Prepare inputs
                prev_actions_oh = tf.one_hot([a], self.n_arms)
                inputs = {
                    'prev_rewards': tf.constant([[rch]], dtype=tf.float32),
                    'prev_actions': prev_actions_oh
                }
                
                # Forward pass
                try:
                    if self.entropy_loss_weight == 'linear':
                        current_entropy = entr_
                    else:
                        current_entropy = self.entropy_loss_weight
                    
                    a_dist, v, rnn_state_new = self.ac_network(
                        inputs, rnn_state, tf.constant(h_noise, dtype=tf.float32), training=train
                    )
                        
                except Exception as e:
                    print(f"ERROR in forward pass at episode {episode_count}, timestep {t}: {e}")
                    import traceback
                    traceback.print_exc()
                    raise
                
                # Sample action
                a_dist_np = a_dist.numpy()[0]
                a = np.random.choice(len(a_dist_np), p=a_dist_np)
                
                # Update state
                rnn_state = rnn_state_new
                
                # Environment step
                rch, d, t = self.env.pull_arm(a)
                
                episode_reward += rch
                episode_step_count += 1
                
                # Store transition
                if self.learning_algorithm == 'a2c':
                    v_val = v.numpy()[0, 0]
                else:
                    v_val = 0.0
                
                episode_buffer.append([a, rch, t, h_noise[0], v_val, d])
                
                # Collect test data
                if train == False:
                    my_a.append(a)
                    my_rch.append(rch)
                    my_r_prob[t] = self.env.reward_probs[t]
                    rnn_softmax_arr[t] = a_dist_np
                    rnn_value_arr[t] = v_val
                
                # Update environment
                if not d:
                    self.env.update()
            
            # Episode complete
            self.episode_rewards.append(episode_reward)
            self.episode_lengths.append(episode_step_count)
            
            # Training update
            if len(episode_buffer) != 0 and train == True:
                try:
                    if self.learning_algorithm == 'a2c':
                        v_l, p_l, e_l, g_n, v_n, gg = self.train_step(episode_buffer, gamma, 0.0, entr_)
                    else:
                        p_l, e_l, g_n, v_n, gg = self.train_step(episode_buffer, gamma, 0.0, entr_)
                        
                except Exception as e:
                    print(f"ERROR in train_step at episode {episode_count}: {e}")
                    import traceback
                    traceback.print_exc()
                    raise
            
            # Return test results
            if train == False:
                df['choice'] = my_a
                df['reward'] = my_rch
                df['value'] = rnn_value_arr
                df[rnn_prob_rew] = my_r_prob
                df[rnn_state_col_names] = rnn_state_arr
                df[rnn_state_noise_col_names] = rnn_state_noise_arr
                df[rnn_softmax] = rnn_softmax_arr
                df[bandit_par] = self.env.game.bandit_parameter
                return df
            
            # Save checkpoints
            if episode_count != 0:
                if episode_count % 500 == 0 and train == True:
                    if not os.path.exists(self.model_path):
                        os.makedirs(self.model_path)
                    
                    checkpoint.save(os.path.join(self.model_path, f'model-{episode_count}'))
                    print(f"Saved Model Episodes: {episode_count}")
                    mean_reward = np.mean(self.episode_rewards[-50:])
                    print(f'mean_reward: {mean_reward}')
                
                if train == True and episode_count > 0 and episode_count % self.n_iterations == 0:
                    print(f"Reached target iterations ({self.n_iterations}). Stopping training.")
                    return None
                
                # TensorBoard logging
                mean_reward = np.mean(self.episode_rewards[-50:])
                
                with self.summary_writer.as_default():
                    tf.summary.scalar('Perf/Reward', mean_reward, step=episode_count)
                    if train == True:
                        tf.summary.scalar('Losses/Policy Loss', p_l, step=episode_count)
                        tf.summary.scalar('Losses/Entropy', e_l, step=episode_count)
                        tf.summary.scalar('Losses/Var Norm', v_n, step=episode_count)
                        tf.summary.scalar('Gradnorm', gg, step=episode_count)
            
            episode_count += 1
            entr_ = max(0.0, entr_ - 1.0 / self.n_iterations)
            
            # Debug: print episode count every 100 episodes
            if train and episode_count % 100 == 0:
                print(f"Episode {episode_count}/{self.n_iterations}")


class neural_network:
    """
    Neural network class for training and testing a reinforcement learning model.
    
    This is the main interface for creating, training, and testing RNN agents
    on bandit tasks.
    
    Parameters
    ----------
    bandit : instance of bandit_class.Bandit
        The bandit object that defines the task for the agent to learn.
    noise : str, optional
        Type of computational noise ('none', 'update-dependant', 'constant').
        Default is 'none'.
    noise_parameter : float, optional
        The strength of the noise to apply (Weber fraction). Default is 0.
    entropy_loss_weight : float or str, optional
        The weight of the entropy loss or 'linear'. Default is 0.
    value_loss_weight : float, optional
        The weight of the value loss. Default is 0.
    rnn_type : str, optional
        Type of RNN cell ('lstm', 'lstm2', 'rnn'). Default is 'rnn'.
    learning_algorithm : str, optional
        Learning algorithm ('a2c', 'reinforce'). Default is 'reinforce'.
    discount_rate : float, optional
        The discount rate. Default is 0.5.
    learning_rate : float, optional
        The learning rate. Default is 1e-4.
    n_hidden_neurons : int, optional
        The number of neurons in the hidden layer. Default is 48.
    n_iterations : int, optional
        The number of training iterations. Default is 50000.
    path_to_save_model : str, optional
        Path to save trained models. Default is 'saved_models/'.
    path_to_save_progress : str, optional
        Path to save training progress. Default is 'tensorboard/'.
    path_to_save_test_files : str, optional
        Path to save test results. Default is 'data/rnn_raw_data/'.
    model_id : int, optional
        An identifier for the model. Default is 0.
        
    Methods
    -------
    train():
        Train the neural network.
    test(n_runs, bandit_param_range, bandit, num_rins, path_to_fixed_bandits):
        Test the neural network.
    reset():
        Reset is not needed in TF2, but kept for compatibility.
    """
    
    def __init__(self, bandit, noise='none', noise_parameter=0,
                 entropy_loss_weight=0, value_loss_weight=0, rnn_type='rnn',
                 learning_algorithm='reinforce', discount_rate=0.5,
                 learning_rate=1e-4, n_hidden_neurons=48, n_iterations=50000,
                 path_to_save_model='saved_models/',
                 path_to_save_progress='tensorboard/',
                 path_to_save_test_files='data/rnn_raw_data/',
                 model_id=0):
        
        self.bandit = bandit
        self.noise = noise
        self.noise_parameter = noise_parameter
        self.entropy_loss_weight = entropy_loss_weight
        self.value_loss_weight = value_loss_weight
        self.rnn_type = rnn_type
        self.learning_algorithm = learning_algorithm
        self.discount_rate = discount_rate
        self.learning_rate = learning_rate
        self.n_hidden_neurons = n_hidden_neurons
        self.n_iterations = n_iterations
        self.path_to_save_model = path_to_save_model
        self.path_to_save_progress = path_to_save_progress
        self.path_to_save_test_files = path_to_save_test_files
        self.model_id = model_id
        
        # Apply noise parameter
        if self.noise == 'update-dependant':
            self.noise_parameter = self.noise_parameter
        elif self.noise == 'constant':
            raise ValueError('Constant noise is not implemented yet!')
        elif self.noise == 'none':
            self.noise_parameter = 0
        
        # Create model name
        self.model_name = '{}_{}_nh_{}_lr_{}_n_{}_p_{}_ew_{}_vw_{}_dr_{}_{}_d_{}_p_{}_rt_{}_a_{}_n_{}_te_{}_id_{}'.format(
            self.rnn_type,
            self.learning_algorithm[0:3],
            self.n_hidden_neurons,
            dot2_(self.learning_rate, is_lr=True),
            self.noise[0],
            dot2_(self.noise_parameter),
            dot2_(self.entropy_loss_weight),
            dot2_(self.value_loss_weight),
            dot2_(self.discount_rate),
            self.bandit.bandit_type[0:3],
            str(self.bandit.dependant)[0],
            dot2_(self.bandit.bandit_parameter),
            self.bandit.reward_type[0:3],
            self.bandit.arms,
            self.bandit.num_steps,
            self.n_iterations,
            self.model_id
        ).lower()
        
        self.model_path = self.path_to_save_model + self.model_name
        
        # Create optimizer
        self.optimizer = tf.keras.optimizers.RMSprop(learning_rate=self.learning_rate)
    
    def train(self):
        """
        Train the neural network using the specified parameters.
        
        This method initializes the training process. It creates a folder to save
        training progress, sets up the network, and starts training. If a pre-existing
        model exists, training resumes from the last checkpoint.
        """
        train = True
        
        # Create folder to save progress
        if not os.path.exists(self.path_to_save_progress):
            os.makedirs(self.path_to_save_progress)
        
        # Create the worker
        self.worker = Worker(
            game=ConditioningBandit(self.bandit),
            optimizer=self.optimizer,
            model_path=self.model_path,
            model_name=self.model_name,
            noise=self.noise,
            path_to_save_progress=self.path_to_save_progress,
            n_hidden_neurons=self.n_hidden_neurons,
            n_arms=self.bandit.arms,
            num_steps=self.bandit.num_steps,
            n_iterations=self.n_iterations,
            rnn_type=self.rnn_type,
            noise_parameter=self.noise_parameter,
            entropy_loss_weight=self.entropy_loss_weight,
            value_loss_weight=self.value_loss_weight,
            learning_algorithm=self.learning_algorithm
        )
        
        # Create checkpoint
        checkpoint = tf.train.Checkpoint(
            optimizer=self.optimizer,
            model=self.worker.ac_network
        )
        
        # Check if model exists and restore
        if os.path.exists(self.model_path):
            print(f'Resuming Training Model: {self.model_name}')
            latest_checkpoint = tf.train.latest_checkpoint(self.model_path)
            if latest_checkpoint:
                checkpoint.restore(latest_checkpoint)
                print(f'Restored from {latest_checkpoint}')
        else:
            print(f'Training Model: {self.model_name}')
        
        # Train
        result = self.worker.work(self.discount_rate, checkpoint, train)
        print(f"Training complete. Work returned: {result}")
        
        # Reset is not needed in TF2
        # self.reset()
    
    def test(self, n_runs, bandit_param_range, bandit, num_rins=1,
             path_to_fixed_bandits='data/intermediate_data/fixed_bandits/'):
        """
        Test the neural network on multiple runs and bandit parameter ranges.
        
        This method evaluates the trained neural network on various runs and bandit
        parameter ranges.
        
        Parameters
        ----------
        n_runs : int
            The number of runs to test.
        bandit_param_range : array-like
            The range of bandit parameters to test.
        bandit : str
            The bandit file path or definition.
        num_rins : int, optional
            The number of reward instances. Default is 1.
        path_to_fixed_bandits : str, optional
            Path to fixed bandit data. Default is 'data/intermediate_data/fixed_bandits/'.
        """
        train = False
        train_sd = self.bandit.bandit_parameter
        
        for sd_ in bandit_param_range:
            df_list = []
            temp_sd = dot2_(sd_)
            
            for run in range(n_runs):
                bandit_zip_name = bandit.format(temp_sd, str(run))
                
                for rin in range(num_rins):
                    # Load bandit
                    if isinstance(bandit, str) and 'Daw2006' in bandit:
                        df_bandit = pd.read_csv(bandit)
                        self.bandit = fdbc.LoadDawBandit(df_bandit)
                    else:
                        bandit_zip = zip2csv(path_to_data=path_to_fixed_bandits,
                                            zip_file_name=bandit_zip_name)
                        bandit_file_name = bandit_zip_name.replace('.zip',
                                                                   f'_rin_{str(rin)}.csv')
                        bandit_zip.extract_file(bandit_file_name)
                        fixed_test_bandit = pd.read_csv(bandit_file_name)
                        self.bandit = fbc.LoadBandit(fixed_test_bandit)
                        self.bandit.bandit_parameter = sd_
                        bandit_zip.delete_file(bandit_file_name)
                    
                    # Create worker
                    self.worker = Worker(
                        game=ConditioningBandit(self.bandit),
                        optimizer=self.optimizer,
                        model_path=self.model_path,
                        model_name=self.model_name,
                        noise=self.noise,
                        path_to_save_progress=self.path_to_save_progress,
                        n_hidden_neurons=self.n_hidden_neurons,
                        n_arms=self.bandit.arms,
                        num_steps=self.bandit.num_steps,
                        n_iterations=self.n_iterations,
                        rnn_type=self.rnn_type,
                        noise_parameter=self.noise_parameter,
                        entropy_loss_weight=self.entropy_loss_weight,
                        value_loss_weight=self.value_loss_weight,
                        learning_algorithm=self.learning_algorithm
                    )
                    
                    # Create checkpoint
                    checkpoint = tf.train.Checkpoint(
                        optimizer=self.optimizer,
                        model=self.worker.ac_network
                    )
                    
                    # Restore model
                    latest_checkpoint = tf.train.latest_checkpoint(self.model_path)
                    print(self.model_path)
                    
                    if latest_checkpoint:
                        checkpoint.restore(latest_checkpoint)
                        print(f'Restored from {latest_checkpoint}')
                    
                    # Test
                    df = self.worker.work(self.discount_rate, checkpoint, train)
                    
                    # Create multi-indexed dataframe
                    df['rnn_type'] = self.rnn_type
                    df['noise'] = self.noise
                    df['entropy_loss_weight'] = self.entropy_loss_weight
                    df['value_loss_weight'] = self.value_loss_weight
                    df['learning_algorithm'] = self.learning_algorithm
                    df['train_sd'] = train_sd
                    df['run'] = run
                    df['reward_instance'] = rin
                    df['test_sd'] = self.bandit.bandit_parameter
                    df['rnn_id'] = self.model_id
                    
                    # Calculate accuracy
                    accuracy = [int(ch == np.argmax([p1, p2, p3, p4]))
                               for ch, p1, p2, p3, p4 in zip(df['choice'],
                                                             df['p_rew_1'],
                                                             df['p_rew_2'],
                                                             df['p_rew_3'],
                                                             df['p_rew_4'])]
                    df['accuracy'] = accuracy
                    
                    # Determine switches
                    is_switch = [int(df.choice[t] != df.choice[t-1])
                                for t in range(1, len(df['choice']))]
                    is_switch = np.append(0, is_switch)
                    df['is_switch'] = is_switch
                    
                    df_list.append(df)
                    
                    print('ACCURACY')
                    print(np.mean(df['accuracy']))
                    
                    # Reset is not needed in TF2
                    # self.reset()
                
                # Save results
                multiindex_list = ['rnn_type', 'learning_algorithm', 'noise', 'train_sd',
                                  'rnn_id', 'test_sd', 'run', 'reward_instance']
                
                all_dfs = pd.concat(df_list)
                mult_ind_df = all_dfs.set_index(multiindex_list)
                
                filename = (self.path_to_save_test_files + self.model_name +
                           f'_test_b_{self.bandit.bandit_type[0:3]}_p_{temp_sd}')
                
                outfile = open(filename, 'wb')
                pickle.dump(mult_ind_df, outfile)
                outfile.close()
                
                print('FINISHED')
    
